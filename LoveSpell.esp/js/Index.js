// =====================================================
// CAMBIAR IDIOMA
// =====================================================

function changeLanguage(language) {

  // Verificamos que exista el idioma
  if (!translations[language]) {
    return;
  }

  // Buscamos todos los elementos que tengan data-i18n
  const elements = document.querySelectorAll("[data-i18n]");

  elements.forEach(element => {

    const key = element.getAttribute("data-i18n");

    if (translations[language][key]) {
      element.textContent = translations[language][key];
    }

  });


  // Cambiamos el idioma del documento
  document.documentElement.lang = language;


  // Marcamos el botón activo
  document.querySelectorAll(".lang-pill").forEach(button => {

    button.classList.toggle(
      "active",
      button.getAttribute("data-lang") === language
    );

  });


  // Guardamos el idioma elegido
  localStorage.setItem("loveSpellLanguage", language);
}


// =====================================================
// BOTONES ES / EN / FR
// =====================================================

const languageButtons = document.querySelectorAll(".lang-pill");

languageButtons.forEach(button => {

  button.addEventListener("click", () => {

    const language = button.getAttribute("data-lang");

    changeLanguage(language);

  });

});


// =====================================================
// MENÚ HAMBURGUESA
// =====================================================

const menuBtn = document.getElementById("menuBtn");
const mobileMenu = document.getElementById("mobileMenu");
const menuBackdrop = document.getElementById("menuBackdrop");


function openMenu() {

  menuBtn.setAttribute("aria-expanded", "true");

  mobileMenu.setAttribute("aria-hidden", "false");

  menuBtn.classList.add("is-open");

  mobileMenu.classList.add("is-open");

  menuBackdrop.classList.add("is-open");

  document.body.classList.add("menu-open");
}


function closeMenu() {

  menuBtn.setAttribute("aria-expanded", "false");

  mobileMenu.setAttribute("aria-hidden", "true");

  menuBtn.classList.remove("is-open");

  mobileMenu.classList.remove("is-open");

  menuBackdrop.classList.remove("is-open");

  document.body.classList.remove("menu-open");
}


menuBtn.addEventListener("click", () => {

  const isOpen =
    menuBtn.getAttribute("aria-expanded") === "true";

  if (isOpen) {
    closeMenu();
  } else {
    openMenu();
  }

});


menuBackdrop.addEventListener("click", closeMenu);


mobileMenu.querySelectorAll("a").forEach(link => {

  link.addEventListener("click", closeMenu);

});


document.addEventListener("keydown", event => {

  if (event.key === "Escape") {
    closeMenu();
  }

});


